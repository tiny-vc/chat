import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const config = JSON.parse(await readFile(resolve(root, "branding.json"), "utf8"));
const appName = String(config.appName ?? "").trim();
const tagline = String(config.tagline ?? "").trim();
const primaryColor = String(config.primaryColor ?? "").trim().toUpperCase();

if (!appName || appName.length > 30 || /[\r\n]/.test(appName)) {
  throw new Error("branding.json appName must contain 1-30 characters on one line");
}
if (!tagline || tagline.length > 80 || /[\r\n]/.test(tagline)) {
  throw new Error("branding.json tagline must contain 1-80 characters on one line");
}
if (!/^#[0-9A-F]{6}$/.test(primaryColor)) {
  throw new Error("branding.json primaryColor must use #RRGGBB");
}

const dartString = (value) => value.replaceAll("\\", "\\\\").replaceAll("'", "\\'");
const tsString = (value) => JSON.stringify(value);
const xmlString = (value) => value
  .replaceAll("&", "&amp;")
  .replaceAll("<", "&lt;")
  .replaceAll(">", "&gt;")
  .replaceAll('"', "&quot;")
  .replaceAll("'", "&apos;");

await writeFile(
  resolve(root, "apps/flutter_chat/lib/config/branding.g.dart"),
  `// Generated by scripts/sync-branding.mjs. Do not edit.\nabstract final class GeneratedBranding {\n  static const appName = '${dartString(appName)}';\n  static const tagline = '${dartString(tagline)}';\n  static const primaryColorValue = 0xFF${primaryColor.slice(1)};\n}\n`,
);
await writeFile(
  resolve(root, "apps/flutter_chat/android/app/src/main/res/values/branding.xml"),
  `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/sync-branding.mjs. Do not edit. -->\n<resources>\n    <string name="app_name">${xmlString(appName)}</string>\n</resources>\n`,
);
await writeFile(
  resolve(root, "apps/flutter_chat/ios/Flutter/Branding.xcconfig"),
  `// Generated by scripts/sync-branding.mjs. Do not edit.\nAPP_DISPLAY_NAME = ${appName}\n`,
);
await writeFile(
  resolve(root, "apps/admin_web/src/branding.ts"),
  `// Generated by scripts/sync-branding.mjs. Do not edit.\nexport const appName = ${tsString(appName)};\nexport const adminAppName = ${tsString(`${appName}管理平台`)};\nexport const tagline = ${tsString(tagline)};\nexport const primaryColor = ${tsString(primaryColor.toLowerCase())};\n`,
);

const indexPath = resolve(root, "apps/admin_web/index.html");
const index = await readFile(indexPath, "utf8");
await writeFile(
  indexPath,
  index
    .replace(/<meta name="theme-color" content="[^"]*" \/>/, `<meta name="theme-color" content="${primaryColor.toLowerCase()}" />`)
    .replace(/<title>[^<]*<\/title>/, `<title>${xmlString(appName)}管理平台</title>`),
);

console.log(`Branding synchronized: ${appName}, ${primaryColor}`);
